/**
 * Renders results/REPORT.md from every results/*.json present.
 *
 * Called after EVERY target, not at the end: a sweep that dies at hour four still
 * leaves a complete, honest report for the targets it finished.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { BENCHMARKED } from '../contract/requests.ts';
import { TARGETS } from '../contract/targets.ts';
import type { TargetResult, SkipRecord } from './types.ts';

const ROOT = new URL('..', import.meta.url).pathname;
const RESULTS = join(ROOT, 'results');

const n0 = (v: number) => (Number.isFinite(v) ? Math.round(v).toLocaleString('en-US') : '—');
const n2 = (v: number) => (Number.isFinite(v) ? v.toFixed(2) : '—');

export async function loadResults(): Promise<TargetResult[]> {
  if (!existsSync(RESULTS)) return [];
  const files = (await readdir(RESULTS)).filter((f) => f.endsWith('.json') && f !== 'report.json' && f !== 'skips.json');
  const out: TargetResult[] = [];
  for (const f of files) {
    try {
      out.push(JSON.parse(await readFile(join(RESULTS, f), 'utf8')));
    } catch {
      /* a half-written file from a killed sweep is not fatal */
    }
  }
  return out;
}

async function loadSkips(): Promise<SkipRecord[]> {
  const p = join(RESULTS, 'skips.json');
  if (!existsSync(p)) return [];
  try {
    return JSON.parse(await readFile(p, 'utf8'));
  } catch {
    return [];
  }
}

function header(results: TargetResult[]): string {
  const p = results[0]?.profile;
  const reps = results[0]?.reps ?? 3;
  return [
    '# AsenaJS Benchmark Report',
    '',
    '> Generated by `bun run-all.ts`. Every number below comes from a target that passed',
    '> byte-for-byte conformance first — see `BENCHMARK_PLAN.md` for the frozen contract.',
    '',
    '## Methodology',
    '',
    '| | |',
    '|---|---|',
    `| Hardware | AMD Ryzen 9 9950X3D · 16C/32T · 60 GB RAM |`,
    `| Load generator | \`wrk\`, pinned to cores 16-31 |`,
    `| Server | pinned to cores 0-7, single process, no clustering |`,
    `| Profile | \`${p?.name ?? '—'}\` — ${p ? `${p.threads} threads, ${p.connections} connections, ${p.duration}s` : '—'} |`,
    `| Warmup | ${p?.warmup ?? '—'}s before every measurement |`,
    `| Repetitions | ${reps} per scenario, fresh process each — ` +
      (reps === 1
        ? 'single observation, no spread available |'
        : reps === 2
          ? '**mean of the two** reported, spread shown per row |'
          : '**median** reported, spread shown per row |'),
    `| Write scenarios | capped at ${p?.writeDuration ?? '—'}s — DB-bound, not framework-bound |`,
    `| Database | PostgreSQL, \`synchronous_commit = off\`, pool size 20, 10,000 seeded rows |`,
    `| Generated | ${new Date().toISOString()} |`,
    '',
    '::: warning',
    'The `/db/*` layer is **not** uniform across apps — it is each stack\'s idiomatic choice',
    '(`pg`, `Bun.sql`, TypeORM, drizzle). Every table below labels it. The clean',
    'framework-vs-framework database signal is the set of rows sharing one layer.',
    ':::',
    '',
  ].join('\n');
}

function scenarioTable(results: TargetResult[], id: string, label: string): string {
  const rows = results
    .map((t) => ({ t, s: t.scenarios[id] }))
    .filter((r): r is { t: TargetResult; s: NonNullable<typeof r.s> } => !!r.s && r.s.status === 'ok' && !!r.s.median)
    .sort((a, b) => b.s.median!.rps - a.s.median!.rps);

  if (rows.length === 0) return '';

  const best = rows[0]!.s.median!.rps;
  const lines = [
    `### ${label}  \`${id}\``,
    '',
    '| # | Target | Runtime | Req/sec | vs best | Latency avg | p99 | Layer |',
    '|--:|:---|:---|--:|--:|--:|--:|:---|',
  ];
  rows.forEach((r, i) => {
    const m = r.s.median!;
    const rel = `${((m.rps / best) * 100).toFixed(0)}%`;
    const layer = id.startsWith('s6') ? r.t.dbLayer : id === 's5' ? r.t.validator : '—';
    const name = i === 0 ? `**${r.t.framework}**` : r.t.framework;
    lines.push(
      `| ${i + 1} | ${name} | ${r.t.runtime} | ${i === 0 ? `**${n0(m.rps)}**` : n0(m.rps)} | ${rel} | ${n2(m.latencyAvgMs)} ms | ${n2(m.latencyP99Ms)} ms | ${layer} |`,
    );
  });
  lines.push('');
  return lines.join('\n');
}

function detail(t: TargetResult): string {
  const lines = [
    `### ${t.framework} — \`${t.target}\``,
    '',
    `Runtime \`${t.runtime} ${t.runtimeVersion}\` · db \`${t.dbLayer}\` · validator \`${t.validator}\` · `,
    `measured ${t.startedAt} → ${t.finishedAt}`,
    '',
    '| Scenario | Req/sec | avg | p50 | p90 | p99 | max | Transfer | Spread |',
    '|:---|--:|--:|--:|--:|--:|--:|--:|--:|',
  ];
  for (const r of BENCHMARKED) {
    const s = t.scenarios[r.id];
    if (!s) continue;
    if (s.status !== 'ok' || !s.median) {
      lines.push(`| ${r.id} ${r.scenario} | FAILED | | | | | | | ${s.note ?? ''} |`);
      continue;
    }
    const m = s.median;
    lines.push(
      `| \`${r.id}\` ${r.scenario} | ${n0(m.rps)} | ${n2(m.latencyAvgMs)} | ${n2(m.latencyP50Ms)} | ${n2(m.latencyP90Ms)} | ${n2(m.latencyP99Ms)} | ${n2(m.latencyMaxMs)} | ${n2(m.transferMBps)} MB/s | ${s.rpsSpread !== undefined ? `${(s.rpsSpread * 100).toFixed(1)}%` : '—'} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}

const GROUP_LABELS: Record<string, string> = {
  s1a: 'Hello World — plaintext',
  s1b: 'Hello World — JSON',
  s2a: 'Query string parsing',
  s2b: 'Path parameters',
  s3: 'Comprehensive API endpoint',
  s4a: 'Static file — 4 KB HTML',
  s4b: 'Static file — 256 KB PNG',
  s5: 'Validated endpoint',
  s6a: 'Database — read by id',
  s6b: 'Database — paged list',
  s6c: 'Database — insert',
  's6a-orm': 'Database — read by id (drizzle)',
  's6b-orm': 'Database — paged list (drizzle)',
  's6c-orm': 'Database — insert (drizzle)',
};

export async function render(): Promise<string> {
  const results = await loadResults();
  const skips = await loadSkips();
  const parts = [header(results), '## Results by scenario', ''];

  for (const r of BENCHMARKED) {
    const table = scenarioTable(results, r.id, GROUP_LABELS[r.id] ?? r.scenario);
    if (table) parts.push(table);
  }

  parts.push('## Per-target detail', '');
  for (const t of results.sort((a, b) => a.target.localeCompare(b.target))) parts.push(detail(t));

  const measured = new Set(results.map((t) => t.target));
  const missing = TARGETS.filter((t) => !measured.has(t.id));
  if (missing.length || skips.length) {
    parts.push('## Not measured', '');
    for (const m of missing) {
      const s = skips.find((x) => x.target === m.id);
      parts.push(`- \`${m.id}\` — ${s?.reason ?? 'not run yet'}`);
    }
    parts.push('');
  }

  const failed = results.flatMap((t) =>
    Object.values(t.scenarios)
      .filter((s) => s.status === 'failed')
      .map((s) => `- \`${t.target}\` / \`${s.id}\` — ${s.note ?? 'failed'}`),
  );
  if (failed.length) parts.push('## Failed scenarios', '', ...failed, '');

  return parts.join('\n');
}

export async function write(): Promise<void> {
  const md = await render();
  await writeFile(join(RESULTS, 'REPORT.md'), md);
  const results = await loadResults();
  await writeFile(join(RESULTS, 'report.json'), JSON.stringify(results, null, 2) + '\n');
}

if (import.meta.main) {
  await write();
  console.log('report written to results/REPORT.md');
}
